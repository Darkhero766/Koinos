grant select, insert on table public.issue_events to anon, authenticated;
grant usage, select on sequence public.issue_events_id_seq to anon, authenticated;

alter table public.issues enable row level security;
alter table public.issue_events enable row level security;
alter table public.issue_votes enable row level security;

drop policy if exists "KOINOS public issue read" on public.issues;
create policy "KOINOS public issue read" on public.issues for select to anon, authenticated using (true);
drop policy if exists "KOINOS issue insert" on public.issues;
create policy "KOINOS issue insert" on public.issues for insert to anon, authenticated with check (
  (anonymous = true and owner_user_id is null) or
  (anonymous = false and owner_user_id = auth.uid())
);
drop policy if exists "KOINOS public events read" on public.issue_events;
create policy "KOINOS public events read" on public.issue_events for select to anon, authenticated using (true);
drop policy if exists "KOINOS issue event insert" on public.issue_events;
create policy "KOINOS issue event insert" on public.issue_events for insert to anon, authenticated with check (
  exists (select 1 from public.issues i where i.id = issue_id and (i.owner_user_id = auth.uid() or i.owner_user_id is null))
);

create or replace function public.koinos_upvote_issue(p_issue_id text, p_device_id text)
returns jsonb language plpgsql security definer set search_path = public
as $$
declare changed boolean := false; item public.issues;
begin
  if p_issue_id is null or p_device_id is null or char_length(p_device_id) < 10 then raise exception 'Invalid vote'; end if;
  insert into public.issue_votes(issue_id, device_id) values (p_issue_id, p_device_id) on conflict (issue_id, device_id) do nothing;
  if found then
    changed := true;
    update public.issues set upvotes=upvotes+1, priority=least(100,priority+1), updated_at=now() where id=p_issue_id;
  end if;
  select * into item from public.issues where id=p_issue_id;
  if not found then raise exception 'Issue not found'; end if;
  return jsonb_build_object('id',item.id,'title',item.title,'category',item.category,'description',item.description,
    'locationLabel',item.location_label,'latitude',item.latitude,'longitude',item.longitude,'photoUrl',item.photo_url,
    'anonymous',item.anonymous,'status',item.status,'severity',item.severity,'priority',item.priority,'upvotes',item.upvotes,
    'createdAt',item.created_at,'updatedAt',item.updated_at,'alreadyVoted',not changed);
end; $$;
grant execute on function public.koinos_upvote_issue(text,text) to anon, authenticated;

-- Only an authority can change a civic issue's workflow status.
create or replace function public.koinos_authority_update_issue(p_issue_id text, p_status text, p_note text default '')
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare item public.issues;
begin
  if not exists (select 1 from public.profiles where id = (select auth.uid()) and role = 'authority') then
    raise exception 'Authority access required';
  end if;
  if p_status not in ('reported','in_progress','resolved') then raise exception 'Invalid status'; end if;
  update public.issues
  set status = p_status, updated_at = now()
  where id = p_issue_id
  returning * into item;
  if not found then raise exception 'Issue not found'; end if;
  insert into public.issue_events(issue_id, status, note)
  values (item.id, item.status, nullif(left(coalesce(p_note,''),500),''));
  return jsonb_build_object('id',item.id,'title',item.title,'category',item.category,'description',item.description,
    'locationLabel',item.location_label,'latitude',item.latitude,'longitude',item.longitude,'photoUrl',item.photo_url,
    'anonymous',item.anonymous,'status',item.status,'severity',item.severity,'priority',item.priority,'upvotes',item.upvotes,
    'createdAt',item.created_at,'updatedAt',item.updated_at);
end;
$$;
revoke execute on function public.koinos_authority_update_issue(text,text,text) from public, anon;
grant execute on function public.koinos_authority_update_issue(text,text,text) to authenticated;
