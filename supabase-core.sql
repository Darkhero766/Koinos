-- KOINOS core database for the static site.
-- Run this once in Supabase SQL Editor. Safe to re-run.

create table if not exists public.issues (
  id text primary key, title text not null, category text not null default 'other', description text not null default '',
  location_label text, latitude double precision, longitude double precision, photo_url text,
  anonymous boolean not null default false, owner_user_id uuid, status text not null default 'reported',
  severity text not null default 'low', priority integer not null default 0, upvotes integer not null default 0,
  created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
alter table public.issues add column if not exists owner_user_id uuid;
alter table public.issues add column if not exists photo_url text;
alter table public.issues add column if not exists anonymous boolean not null default false;
alter table public.issues add column if not exists status text not null default 'reported';
alter table public.issues add column if not exists severity text not null default 'low';
alter table public.issues add column if not exists priority integer not null default 0;
alter table public.issues add column if not exists upvotes integer not null default 0;
alter table public.issues add column if not exists created_at timestamptz not null default now();
alter table public.issues add column if not exists updated_at timestamptz not null default now();
create index if not exists issues_owner_idx on public.issues(owner_user_id);
create index if not exists issues_geo_idx on public.issues(latitude, longitude);
create index if not exists issues_status_idx on public.issues(status);
create index if not exists issues_priority_idx on public.issues(priority desc);

create table if not exists public.issue_events (
  id bigint generated by default as identity primary key,
  issue_id text not null references public.issues(id) on delete cascade,
  status text not null, note text, created_at timestamptz not null default now()
);
create index if not exists issue_events_issue_idx on public.issue_events(issue_id, created_at);
create table if not exists public.issue_votes (
  issue_id text not null references public.issues(id) on delete cascade,
  device_id text not null, created_at timestamptz not null default now(), primary key(issue_id, device_id)
);

-- Authority roles. Promote trusted staff by changing profiles.role to 'authority'
-- in Supabase SQL Editor; do not expose role editing to the browser.
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  display_name text,
  role text not null default 'citizen' check (role in ('citizen','authority')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create or replace function public.handle_koinos_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiles(id, display_name)
  values (new.id, coalesce(new.raw_user_meta_data ->> 'display_name', split_part(new.email, '@', 1)))
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_koinos_auth_user_created on auth.users;
create trigger on_koinos_auth_user_created
after insert on auth.users
for each row execute procedure public.handle_koinos_new_user();

alter table public.profiles enable row level security;
drop policy if exists "KOINOS profile self read" on public.profiles;
create policy "KOINOS profile self read" on public.profiles for select to authenticated using ((select auth.uid()) = id);

grant select on table public.profiles to authenticated;

